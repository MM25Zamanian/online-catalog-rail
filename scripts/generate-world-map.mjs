import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const DottedMap = require("dotted-map").default ?? require("dotted-map");

const __dirname = dirname(fileURLToPath(import.meta.url));
const generatedModuleFile = resolve(
  __dirname,
  "../src/generated/world-map-dots.ts"
);
const svgFile = resolve(__dirname, "../public/world-map-dots.svg");

const map = new DottedMap({
  height: 60,
  grid: "diagonal",
});

const svg = map.getSVG({
  radius: 0.16,
  color: "#fff5",
  shape: "circle",
  backgroundColor: "transparent",
});

const basePath =
  process.env.NEXT_PUBLIC_BASE_PATH || process.env.BUILD_LOCALE
    ? "/" + process.env.BUILD_LOCALE
    : "";

const generatedModule = `// This file is generated by scripts/generate-world-map.mjs.
// Do not edit it by hand.

export const worldMapDotsSrc = "${basePath}/world-map-dots.svg";
`;

await mkdir(dirname(generatedModuleFile), { recursive: true });
await mkdir(dirname(svgFile), { recursive: true });
await writeFile(generatedModuleFile, generatedModule);
await writeFile(svgFile, svg);

console.log(`Generated ${generatedModuleFile}`);
console.log(`Generated ${svgFile}`);
